function cleanString(s: string): string {
  return (s || '').toLowerCase().replace(/\\/g, '').replace(/[^a-z0-9]/g, '')
}

function getTokens(s: string): string[] {
  return (s || '').toLowerCase().replace(/\\/g, '').replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean)
}

export function matchWorkerToNikRecord(workerName: string): NoKaryawanRecord | null {
  const clean = cleanString(workerName)
  if (!clean) return null

  for (const item of NO_KARYAWAN_LIST) {
    const nkClean = cleanString(item.nama)
    if (clean === nkClean) return item

    if (NAME_ALIAS_MAP[nkClean] && NAME_ALIAS_MAP[nkClean].includes(clean)) {
      return item
    }

    const nkTokens = getTokens(item.nama)
    const wTokens = getTokens(workerName)
    let mCount = 0
    nkTokens.forEach(t1 => {
      if (wTokens.some(t2 => t1 === t2 || (t1.length >= 3 && t2.length >= 3 && (t1.startsWith(t2) || t2.startsWith(t1))))) {
        mCount++
      }
    })
    if (mCount === nkTokens.length) {
      return item
    }
  }
  return null
}

export function isTempWorkerNo(noKaryawan?: string): boolean {
  if (!noKaryawan || noKaryawan === '-') return true
  return /^w[-_]/i.test(noKaryawan.trim())
}
